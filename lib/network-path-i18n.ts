export function translate(lang: NpLang, text: string): string {
  if (lang === "en" || !text) return text;
  const hit = ZH[text];
  if (hit !== undefined) return hit;
  const t: Translate = (value) => translate(lang, value);
  for (const [pattern, format] of PATTERNS) {
    const match = text.match(pattern);
    if (match) return format(match, t);
  }
  return text;
}

export function useNpI18n() {
  const { language, setLanguage } = useLanguage();
  const lang: NpLang = language === "zh" ? "zh" : "en";
  const t = useCallback<Translate>((text) => translate(lang, text), [lang]);
  return { lang, setLang: setLanguage as (lang: NpLang) => void, t, isZh: lang === "zh" };
}
